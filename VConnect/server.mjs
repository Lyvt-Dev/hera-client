import {mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {createStore} from './store.mjs';
import {createHttpServer} from './transport.mjs';
await mkdir(new URL('./.local/',import.meta.url),{recursive:true});
const production=process.env.NODE_ENV==='production',publicOrigin=process.env.PUBLIC_ORIGIN;
if(production&&(!publicOrigin||new URL(publicOrigin).protocol!=='https:'))throw new Error('Production requires an HTTPS PUBLIC_ORIGIN.');
const store=createStore(process.env.VCONNECT_DATABASE||fileURLToPath(new URL('./.local/vconnect.sqlite',import.meta.url)),{demo:process.env.VCONNECT_DEMO==='1'||(!production&&process.env.VCONNECT_DEMO!=='0')});
const server=createHttpServer({store,production,publicOrigin,liveReload:!production&&process.env.VCONNECT_LIVE_RELOAD!=='0'});
server.listen(Number(process.env.PORT||4173),process.env.HOST||'127.0.0.1',()=>console.log(`Local: http://localhost:${server.address().port}`));
